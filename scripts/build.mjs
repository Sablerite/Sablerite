// Builds the whole profile: fetches public activity, renders every SVG in a
// light and a dark variant, and writes README.md. No dependencies; Node 20+.
//   node scripts/build.mjs            fetch fresh data, then build
//   node scripts/build.mjs --offline  build from data/snapshot.json only

import { writeFile, readFile, readdir, unlink, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import cfg from '../profile.config.mjs';
import { THEMES, esc } from './lib/util.mjs';
import { collect, languageShares, growthZones, activity } from './lib/data.mjs';
import { renderHero } from './lib/hero.mjs';
import { renderSpecimen } from './lib/specimen.mjs';
import { renderCard, cardHeight, slug } from './lib/cards.mjs';
import { renderSpectrum } from './lib/spectrum.mjs';
import { renderStrata } from './lib/strata.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const ASSETS = join(ROOT, 'assets');
const SNAPSHOT = join(ROOT, 'data', 'snapshot.json');
const offline = process.argv.includes('--offline');

const data = offline ? JSON.parse(await readFile(SNAPSHOT, 'utf8')) : await collect(cfg, SNAPSHOT);
const spectrum = languageShares(data.repos);
const zones = growthZones(data.repos);
const act = activity(data.days);
const repoInfo = new Map(data.repos.map((r) => [r.name, r]));

await mkdir(ASSETS, { recursive: true });
const written = new Set();
const out = async (name, svg) => {
  written.add(name);
  await writeFile(join(ASSETS, name), svg);
};

const height = cardHeight(cfg.collection);
for (const theme of Object.values(THEMES)) {
  const sfx = `-${theme.name}.svg`;
  await out('hero' + sfx, renderHero(cfg, theme));
  await out('specimen' + sfx, renderSpecimen(cfg, theme, zones));
  await out('spectrum' + sfx, renderSpectrum(theme, spectrum));
  await out('strata' + sfx, renderStrata(theme, act, cfg.accounts));
  for (const card of cfg.collection) {
    const info = repoInfo.get(card.repo);
    await out(`card-${slug(card.title)}${sfx}`, renderCard(card, theme, { height, stars: info?.stars, year: info?.created.slice(0, 4) ?? card.year }));
  }
}
// Remove cards that are no longer in the config.
for (const file of await readdir(ASSETS)) if (file.endsWith('.svg') && !written.has(file)) await unlink(join(ASSETS, file));

// ---- README ----------------------------------------------------------------

const picture = (name, alt, width = '100%') =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${name}-dark.svg"><img src="assets/${name}-light.svg" width="${width}" alt="${esc(alt)}"></picture>`;
const gh = (repo) => `https://github.com/${repo}`;

const cards = [];
for (let i = 0; i < cfg.collection.length; i += 2) {
  const pair = cfg.collection.slice(i, i + 2).map((c) => `<a href="${gh(c.repo)}">${picture(`card-${slug(c.title)}`, `${c.title}: ${c.blurb}`, '49%')}</a>`);
  cards.push(`<p>\n${pair.join('\n')}\n</p>`);
}

const drawer = (cfg.drawer || []).map((d) => `[${d.text}](${gh(d.repo)})${d.after || ''}`);
const drawerSentence = !drawer.length
  ? ''
  : drawer.length === 1
    ? `Also in the drawer: ${drawer[0]}.`
    : `Also in the drawer: ${drawer.slice(0, -1).join('; ')}; and ${drawer.at(-1)}.`;

const links = (cfg.links || []).map((l) => `[${l.label}](${l.href})`).join('&ensp;&ensp;');
const owners = cfg.accounts.map((a) => `[@${a}](https://github.com/${a})`).join(' and ');

const readme = `<!-- Generated by scripts/build.mjs from profile.config.mjs. Edit those; this file is overwritten. -->

${picture('hero', `${cfg.user}, ${cfg.hero.pronunciation} ${cfg.hero.partOfSpeech}. ${cfg.hero.senses.map((s, i) => `${i + 1}. ${s}`).join(' ')}`)}

${cfg.intro}

### Specimen data

${picture('specimen', cfg.specimen.fields.map((x) => `${x.label}: ${x.formula ? x.formula.replace(/_/g, '') : x.value}`).join(' '))}

### In the collection

${cards.join('\n\n')}
${drawerSentence ? `\n${drawerSentence}\n` : ''}
### Assay

${picture('spectrum', 'Language spectrum: ' + spectrum.shares.slice(0, 6).map((l) => `${l.lang} ${(l.share * 100).toFixed(0)}%`).join(', '))}

${picture('strata', `Activity cross-section: ${act.total} contributions ${act.since ? 'since ' + act.since.slice(0, 7) : 'in the last year'}.`)}

<sub>The spectrum and the cross-section regrow every day from public activity on ${owners}.</sub>
${links ? `\n<br>\n\n${links}\n` : ''}${cfg.signoff ? `\n<p align="right"><em>${esc(cfg.signoff)}</em></p>\n` : ''}`;
await writeFile(join(ROOT, 'README.md'), readme);

console.log(
  `Built ${written.size} assets. ${act.total} contributions, ${spectrum.voters} repositories, ` +
    `top languages ${spectrum.shares.slice(0, 4).map((l) => `${l.lang} ${(l.share * 100).toFixed(1)}%`).join(', ')}.`,
);
